// Stores are generated by testdata/kvstore/phkv/generate_phkv.py.

import "#src/kvstore/http/register_frontend.js";
import "#src/kvstore/phkv/register_frontend.js";
import "#src/kvstore/vzip/register_frontend.js";
import { describe, expect, test } from "vitest";
import { expandPhkvSchemeUrl } from "#src/kvstore/phkv/scheme.js";
import { parsePipelineUrlComponent } from "#src/kvstore/url.js";
import { constantFixture } from "#tests/fixtures/fixture.js";
import { httpServerFixture } from "#tests/fixtures/http_server.js";
import { getTestFiles, TEST_DATA_DIR } from "#tests/kvstore/test_data.js";
import {
  readAllFromKvStore,
  sharedKvStoreContext,
  testAutoDetect,
  testKvStore,
} from "#tests/kvstore/test_util.js";

const serverFixture = httpServerFixture(constantFixture(TEST_DATA_DIR));

async function url(store: string, key = "") {
  return (await serverFixture.serverUrl()) + `phkv/${store}|phkv:${key}`;
}

async function readBytes(store: string, key: string) {
  const { kvStoreContext } = await sharedKvStoreContext();
  const response = await kvStoreContext.read(await url(store, key), {
    throwIfMissing: true,
  });
  return new Uint8Array(await response.response.arrayBuffer());
}

async function read(store: string, key: string) {
  return new TextDecoder().decode(await readBytes(store, key));
}

// The same keys stored in different ways: records with their values inline or
// not, one page or many, and sections stored, deflated or compressed with
// Zstandard (the writer's default).
const FILES_STORES = [
  "files.phkv",
  "files_paged.phkv",
  "files_out_of_line.phkv",
  "files_stored_sections.phkv",
  "files_deflate_sections.phkv",
];

for (const store of FILES_STORES) {
  describe(store, () => {
    describe("kvstore operations", () => {
      testKvStore(() => url(store));
    });

    test("every key matches the original file", async () => {
      const { kvStoreContext } = await sharedKvStoreContext();
      const kvStore = kvStoreContext.getKvStore(await url(store));
      expect(await readAllFromKvStore(kvStore.store, kvStore.path)).toEqual(
        await getTestFiles(),
      );
    });
  });
}

test("auto-detect", async () => {
  const matches = await testAutoDetect(
    (await serverFixture.serverUrl()) + "phkv/files.phkv",
  );
  expect(matches.map((m) => m.suffix)).toContain("phkv:");
});

test("a vzip archive is not detected as a phkv store", async () => {
  const matches = await testAutoDetect(
    (await serverFixture.serverUrl()) + "vzip/files.vzip",
  );
  expect(matches.map((m) => m.suffix)).not.toContain("phkv:");
});

describe("a phkv store reserves no names", () => {
  test("`__vz__/` keys are ordinary keys", async () => {
    expect(await read("key_source.phkv", "__vz__/first")).toEqual(
      "the bytes of a key source",
    );
    const { kvStoreContext } = await sharedKvStoreContext();
    expect(
      (
        await kvStoreContext.list(await url("key_source.phkv", "__vz__/"), {
          responseKeys: "suffix",
        })
      ).entries,
    ).toEqual([{ key: "first" }]);
  });

  test("a key source can name one", async () => {
    expect(await read("key_source.phkv", "baz/first")).toEqual(
      "the bytes of a key source",
    );
    expect(await read("key_source.phkv", "slice")).toEqual("he");
  });
});

describe("values", () => {
  test("a DEFLATE value and a value outside its record", async () => {
    const value = new Uint8Array(1024).map((_, i) => i % 256);
    expect(await readBytes("values.phkv", "value")).toEqual(value);
    expect(await readBytes("values.phkv", "packed")).toEqual(value);
    expect(await read("values.phkv", "good")).toEqual("good value");
  });

  test("a window of a value", async () => {
    const { kvStoreContext } = await sharedKvStoreContext();
    const response = await kvStoreContext.read(
      await url("values.phkv", "value"),
      {
        throwIfMissing: true,
        byteRange: { offset: 10, length: 20 },
      },
    );
    expect(new Uint8Array(await response.response.arrayBuffer())).toEqual(
      new Uint8Array(20).map((_, i) => i + 10),
    );
  });

  test("a checksum that does not hold is a body error, for the whole value", async () => {
    await expect(readBytes("bad_crc.phkv", "value")).rejects.toThrow(
      /phkv body error.*crc32c/,
    );
    // A window of a stored value is not checked (phkv spec §19.2), and other keys are fine.
    const { kvStoreContext } = await sharedKvStoreContext();
    const response = await kvStoreContext.read(
      await url("bad_crc.phkv", "value"),
      {
        throwIfMissing: true,
        byteRange: { offset: 0, length: 10 },
      },
    );
    expect(response.length).toEqual(10);
    expect(await read("bad_crc.phkv", "good")).toEqual("good value");
  });
});

describe("many keys", () => {
  test("every key is found, and a missing one is not", async () => {
    for (const i of [0, 1, 29, 30, 1234, 2999]) {
      const key = `d/${String(i % 30).padStart(2, "0")}/${String(i).padStart(5, "0")}`;
      expect(await read("many.phkv", key)).toEqual(`value ${i}`);
    }
    expect(await read("many.phkv", "top")).toEqual("top");
    const { kvStoreContext } = await sharedKvStoreContext();
    expect(
      await kvStoreContext.read(await url("many.phkv", "d/00/99999")),
    ).toBe(undefined);
    expect(await kvStoreContext.read(await url("many.phkv", "nothing"))).toBe(
      undefined,
    );
  });

  test("lists a prefix through the page index", async () => {
    const { kvStoreContext } = await sharedKvStoreContext();
    const listing = await kvStoreContext.list(await url("many.phkv", "d/07/"), {
      responseKeys: "suffix",
    });
    expect(listing.entries.length).toEqual(100);
    expect(listing.entries[0]).toEqual({ key: "00007" });
    expect(listing.entries.at(-1)).toEqual({ key: "02977" });
    const top = await kvStoreContext.list(await url("many.phkv"), {
      responseKeys: "suffix",
    });
    expect(top.entries).toEqual([{ key: "top" }]);
    expect(top.directories).toEqual(["d"]);
  });
});

describe("a file that is not a phkv store", () => {
  test("is an archive error", async () => {
    const { kvStoreContext } = await sharedKvStoreContext();
    await expect(
      kvStoreContext.read(
        (await serverFixture.serverUrl()) + "vzip/files.vzip|phkv:a",
        { throwIfMissing: true },
      ),
    ).rejects.toThrow(/phkv archive error: not a phkv store/);
  });
});

describe("phkv:// scheme", () => {
  test("is shorthand for <store-url>|phkv:", async () => {
    const store = (await serverFixture.serverUrl()) + "phkv/files.phkv";
    const { kvStoreContext } = await sharedKvStoreContext();
    const viaScheme = kvStoreContext.getKvStore(`phkv://${store}`);
    expect(viaScheme.store.getUrl(viaScheme.path)).toEqual(`${store}|phkv:`);
    // The store root itself is not a key.
    expect(await kvStoreContext.read(`phkv://${store}`)).toBe(undefined);
  });

  test.for([
    ["https://h/d.phkv", "https://h/d.phkv|phkv:"],
    ["https://h/d.phkv/", "https://h/d.phkv|phkv:"],
    ["https://h/d.phkv/s0/zarr.json", "https://h/d.phkv|phkv:s0/zarr.json"],
    ["https://h/a.phkv/b.phkv/k", "https://h/a.phkv|phkv:b.phkv/k"],
    ["https://data.phkv.org/x.phkv/k", "https://data.phkv.org/x.phkv|phkv:k"],
    ["https://h/store.bin", "https://h/store.bin|phkv:"],
  ] as const)("phkv://%s", ([rest, expected]) => {
    expect(
      expandPhkvSchemeUrl(parsePipelineUrlComponent(`phkv://${rest}`)),
    ).toEqual(expected);
  });

  describe("generic kvstore operations through phkv://", () => {
    testKvStore(
      async () => `phkv://${await serverFixture.serverUrl()}phkv/files.phkv/`,
    );
  });

  test.for([
    ["phkv://", /expected `phkv:\/\/<store-url>`/],
    ["phkv:", /expected `phkv:\/\/<store-url>`/],
    ["phkv://example.com/data.phkv", /the store URL must have a scheme/],
  ] as const)("%s is rejected", async ([url, error]) => {
    const { kvStoreContext } = await sharedKvStoreContext();
    expect(() => kvStoreContext.getKvStore(url)).toThrow(error);
  });
});
